import assert from "node:assert/strict";
import { writeFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { createTestEnv, createExtensionDriver, shellEscape } from "../harness.ts";

const env = createTestEnv();
const fixture = resolve("test/integration/fixtures/faux-interactive.ts");
writeFileSync(join(env.agentDir, "agents", "project-worker.md"), "---\nname: project-worker\ndescription: Offline contract fixture\ntools: read\nauto-exit: true\nextensions: false\nskills: false\n---\nReturn the input literally.\n");
const bin = join(env.root, "bin"); mkdirSync(bin);
writeFileSync(join(bin, "pi"), `#!/bin/bash\nexec ${shellEscape(process.execPath)} ${shellEscape(process.env.PI_TEST_CLI!)} "$@" -e ${shellEscape(fixture)}\n`, { mode: 0o700 });
process.env.PATH = `${bin}:${process.env.PATH}`;
process.env.PI_TEST_SIMPLE = "1";
const driver = await createExtensionDriver(env);
driver.ctx.model = { provider: "interactive-faux", id: "local" };
const call = (tool: string, params: object) => driver.tool(tool).execute("contract", params, undefined, undefined, driver.ctx);
const resultFor = (entry: any) => entry.message?.customType === "subagent_result" && entry.message?.details?.name === "contract";
try {
  const first = await call("subagent", { agent: "project-worker", name: "contract", task: "CONTRACT_FIRST" });
  assert.equal(first.details.status, "started", JSON.stringify(first));
  const path = first.details.sessionFile;
  const saved = JSON.parse(readFileSync(`${path}.loadout.json`, "utf8"));
  assert.equal(saved.model, "interactive-faux/local"); assert.equal(saved.thinking, "off"); assert.equal(saved.cwd, env.dir);
  assert.equal((await call("subagent_status", { name: "contract" })).details.status, "running");
  await assert.rejects(call("subagent_message", { name: "contract", message: "FORBIDDEN_BUSY", resume_only: true }), /running/);
  await driver.waitForMessage(resultFor, { timeout: 15000 });
  const finished = (await call("subagent_status", { name: "contract" })).details;
  assert.equal(finished.id, first.details.id); assert.equal(finished.status, "finished"); assert.match(finished.result, /CONTRACT_FIRST/);
  assert.ok(existsSync(`${path}.result.json`));
  await assert.rejects(call("subagent_status", { name: "foreign" }), /owned/);
  await assert.rejects(call("subagent_message", { name: "contract", message: "FORBIDDEN_CWD", resume_only: true, expected_cwd: env.root }), /cwd/);
  await assert.rejects(call("subagent_message", { name: "contract", message: "FORBIDDEN_AGENT", resume_only: true, expected_agent: "worker" }), /agent/);
  assert.equal((await call("subagent_status", { name: "contract" })).details.status, "finished");
  driver.ctx.model = { provider: "invalid-later", id: "invalid-later" };
  driver.ctx.thinkingLevel = "high";
  const offset = driver.sentMessages.length;
  const resuming = call("subagent_message", { name: "contract", message: "CONTRACT_SECOND", resume_only: true, expected_agent: "project-worker", expected_cwd: env.dir });
  assert.equal((await call("subagent_status", { name: "contract" })).details.status, "running", "a pending resume must not expose the prior finished receipt");
  const resumed = await resuming;
  assert.equal(resumed.details.id, first.details.id);
  assert.ok(!existsSync(`${path}.result.json`), "stale terminal receipt must be gone before new launch returns");
  assert.equal((await call("subagent_status", { name: "contract" })).details.status, "running");
  await driver.waitForMessage(resultFor, { from: offset, timeout: 15000 });
  assert.match((await call("subagent_status", { name: "contract" })).details.result, /CONTRACT_SECOND/);
  assert.deepEqual(JSON.parse(readFileSync(`${path}.loadout.json`, "utf8")), saved);
  assert.doesNotMatch(readFileSync(process.env.PI_TEST_INPUTS!, "utf8"), /FORBIDDEN/);
  assert.deepEqual(JSON.parse(readFileSync(process.env.PI_TEST_MODE!, "utf8")), { mode: "tui", stdin: true, stdout: true });
  await call("subagent_message", { name: "contract", message: "CONTRACT_SHUTDOWN", resume_only: true });
  assert.equal(driver.emittedEvents.length, 0);
} finally { await driver.stop(); }
assert.equal(driver.emittedEvents.filter(event => event.name === "interactive-subagents:disposed").length, 1);
